def unsplash(photo_id):
    return f"https://images.unsplash.com/photo-{photo_id}?auto=format&fit=crop&w=700&q=80"

# O'qish
with open(PROD_FILE, "r", encoding="utf-8") as f:
    text = f.read()

start = text.find('[')
end = text.rfind(']') + 1
products = json.loads(text[start:end])

# Har bir kategoriyaga tegishli mahsulotlarni saralash
cat_products = {}
for p in products:
    cat = p.get('category')
    cat_products.setdefault(cat, []).append(p)

# Yangilash: Har bir mahsulotga to'g'ri, toifasiga mos rasm berish
for cat, prods in cat_products.items():
    pool = CATEGORY_PHOTO_POOLS.get(cat, CATEGORY_PHOTO_POOLS["other_goods"])
    for idx, p in enumerate(prods):
        photo_id = pool[idx % len(pool)]
        img_url = unsplash(photo_id)
        p["image"] = img_url
        p["images"] = [img_url, img_url, img_url]

# products.js ga qayta yozish
with open(PROD_FILE, "w", encoding="utf-8") as f:
    f.write("/**\n * NovaMarket — 528 ta Boy Mahsulotlar Ro'yxati (100% Toifasiga Mos Rasmlar Bilan)\n */\n")
    f.write("export const INITIAL_PRODUCTS = ")
    json.dump(products, f, ensure_ascii=False, indent=2)
    f.write(";\n")

